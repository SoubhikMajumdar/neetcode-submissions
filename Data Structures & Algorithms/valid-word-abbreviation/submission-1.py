import re

class Solution:
    def validWordAbbreviation(self, word: str, abbr: str) -> bool:
        # Split abbr into chunks of digits and characters, keeping the digits.
        # e.g., "a10b" becomes ['a', '10', 'b', ''] or similar
        chunks = re.split(r'(\d+)', abbr)
        
        word_index = 0
        word_len = len(word)
        
        for chunk in chunks:
            if not chunk:
                continue  # Skip empty strings generated by re.split()
                
            if chunk.isdigit():
                # Rule 1: No leading zeros allowed
                if chunk[0] == '0':
                    return False
                
                # Move the pointer forward by the parsed integer value
                steps = int(chunk)
                word_index += steps
            else:
                # Rule 2: Letter chunks must match the word exactly
                chunk_len = len(chunk)
                # Check if we outpaced the word length or characters don't match
                if word_index + chunk_len > word_len or word[word_index:word_index + chunk_len] != chunk:
                    return False
                word_index += chunk_len
                
        # The abbreviation is valid only if we processed the exact length of the word
        return word_index == word_len
